/**
 * Selects 30 questions for an adaptive test (6 from each of the 5 levels).
 */
export function getStage1Questions(track: 'UG' | 'PG', seed = 0): Stage1Question[] {
  const pool = track === 'PG' ? PG_STAGE1_QUESTIONS : UG_STAGE1_QUESTIONS
  const selected: Stage1Question[] = []

  // Group by level 1..5
  for (let lvl = 1; lvl <= 5; lvl++) {
    const levelPool = pool.filter((q) => q.level === lvl)
    // Deterministic or pseudo-random selection of 6 questions per level
    const offset = (seed * 7 + lvl * 3) % levelPool.length
    const picked: Stage1Question[] = []
    for (let i = 0; i < 6; i++) {
      const idx = (offset + i * 2) % levelPool.length
      picked.push(levelPool[idx] || levelPool[i % levelPool.length])
    }
    selected.push(...picked)
  }

  return selected
}

