const fs = require('fs')
const path = require('path')

const mdPath = path.resolve('..', 'stage_1_UG_PG_question_bank.md')
const content = fs.readFileSync(mdPath, 'utf8')

function parseFullBank(rawText) {
  const ugIndex = rawText.indexOf('# Stage 1 UG Adaptive Question Bank')
  const pgHeaderIndex = rawText.indexOf('# PG Bank')
  const pgIndex = rawText.indexOf('# Stage 1 PG Adaptive Question Bank')

  const ugSection = rawText.substring(ugIndex, pgHeaderIndex)
  const pgSection = rawText.substring(pgIndex)

  function parseSection(sectionText, track) {
    const qBlocks = sectionText.split(/###\s+(UG\d+|PG\d+)/g)
    const questions = []

    for (let i = 1; i < qBlocks.length; i += 2) {
      const qId = qBlocks[i].trim()
      const body = qBlocks[i + 1]

      const lines = body.split('\n').map(l => l.trim()).filter(Boolean)
      const questionText = lines[0]

      let type = 'Standard'
      let difficulty = 'Level 1'
      let dimensions = []
      let discriminator = undefined
      let answer = 'A'
      const rawOptions = []

      for (const line of lines) {
        if (line.startsWith('**Type:**')) {
          type = line.replace('**Type:**', '').trim()
        } else if (line.startsWith('**Difficulty:**')) {
          difficulty = line.replace('**Difficulty:**', '').trim()
        } else if (line.startsWith('**Dimensions:**')) {
          dimensions = line.replace('**Dimensions:**', '').split(',').map(d => d.trim()).filter(Boolean)
        } else if (line.startsWith('**Discriminator:**')) {
          discriminator = line.replace('**Discriminator:**', '').trim()
        } else if (line.startsWith('**Answer:**')) {
          answer = line.replace('**Answer:**', '').trim()
        } else if (/^[A-D]\.\s+/.test(line)) {
          const optLetter = line[0]
          const optText = line.substring(2).trim()
          rawOptions.push({ id: optLetter, text: optText })
        }
      }

      // Determine level (1..5)
      let level = 1
      const numMatch = qId.match(/\d+/)
      const qNum = numMatch ? parseInt(numMatch[0], 10) : 1
      if (qNum <= 15) level = 1
      else if (qNum <= 35) level = 2
      else if (qNum <= 60) level = 3
      else if (qNum <= 85) level = 4
      else level = 5

      // Assign dimension weights to options
      // Level 1: Preference questions where each option can have distinct dimension associations or correct answer gets top weight
      const options = rawOptions.map((opt) => {
        const weights = {}
        const isCorrect = opt.id === answer
        
        if (level === 1) {
          // In Level 1 preference questions, option A is aligned with primary dimensions; other options also give partial or domain weights
          if (isCorrect) {
            dimensions.forEach(d => { weights[d] = 5 })
          } else {
            // Secondary distribution
            dimensions.forEach(d => { weights[d] = 1 })
            // Infer secondary dimensions if text hints
            if (/people|social|community/i.test(opt.text)) weights['SO'] = (weights['SO'] || 0) + 4
            if (/business|market|organi/i.test(opt.text)) weights['BU'] = (weights['BU'] || 0) + 4
            if (/design|concept|creative/i.test(opt.text)) weights['CR'] = (weights['CR'] || 0) + 4
            if (/experiment|science|research/i.test(opt.text)) weights['RE'] = (weights['RE'] || 0) + 4
            if (/app|code|prototype|tech/i.test(opt.text)) weights['TC'] = (weights['TC'] || 0) + 4
          }
        } else {
          // Levels 2..5: Objective reasoning / scenario / analytical
          if (isCorrect) {
            dimensions.forEach(d => { weights[d] = 5 })
          } else {
            dimensions.forEach(d => { weights[d] = 1 })
          }
        }

        return {
          id: opt.id,
          text: opt.text,
          weights
        }
      })

      questions.push({
        id: qId,
        number: qNum,
        track,
        level,
        type,
        difficulty,
        dimensions,
        discriminator,
        question: questionText,
        options,
        correctAnswer: answer
      })
    }

    return questions
  }

  const ugQuestions = parseSection(ugSection, 'UG')
  const pgQuestions = parseSection(pgSection, 'PG')

  return { ugQuestions, pgQuestions }
}

const { ugQuestions, pgQuestions } = parseFullBank(content)

console.log(`Successfully parsed ${ugQuestions.length} UG questions and ${pgQuestions.length} PG questions.`)

